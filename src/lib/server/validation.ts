import type { createClient } from "@/lib/supabase/server";
import { ARCHIVED_ACCOUNT_ERROR, archivedAccountBlocks } from "@/lib/accounts";
import { transactionFieldsError, type TransactionFields } from "@/lib/validation/rules";

type ServerClient = Awaited<ReturnType<typeof createClient>>;

/**
 * Full transaction validation used by both createTransactionAction/updateTransactionAction
 * and the offline sync action: field rules plus "is this one of your active accounts" and
 * "is this an available category of the same type". Moved here unchanged from
 * src/app/actions/transactions.ts so the two paths can never drift apart.
 */
export async function validateTransactionInput(
  input: TransactionFields,
  userId: string,
  supabase: ServerClient,
  /** The transaction's current account when editing: it may stay there even if archived. */
  existingAccountId?: string | null
) {
  const fieldError = transactionFieldsError(input);
  if (fieldError) return fieldError;

  const [accountResult, categoryResult] = await Promise.all([
    // "*" keeps working before the archive migration adds archived_at.
    supabase
      .from("accounts")
      .select("*")
      .eq("id", input.accountId)
      .eq("user_id", userId)
      .is("deleted_at", null)
      .maybeSingle(),
    supabase
      .from("categories")
      .select("id")
      .eq("id", input.categoryId)
      .eq("type", input.type)
      .or(`is_default.eq.true,user_id.eq.${userId}`)
      .maybeSingle(),
  ]);

  if (accountResult.error || !accountResult.data) {
    return "Choose one of your active accounts.";
  }
  if (archivedAccountBlocks(accountResult.data as { id: string; archived_at?: string | null }, existingAccountId)) {
    return ARCHIVED_ACCOUNT_ERROR;
  }
  if (categoryResult.error || !categoryResult.data) {
    return "Choose an available category matching the transaction type.";
  }

  return null;
}

/**
 * Whether a transaction is an expense generated by an installment payment, which only the
 * Installments page may change. "error" means the check itself failed (callers must refuse rather
 * than risk desynchronising a payment). Before the Installments migration the table doesn't exist,
 * so nothing is managed.
 */
export async function isInstallmentManagedTransaction(
  supabase: ServerClient,
  userId: string,
  transactionId: string
): Promise<boolean | "error"> {
  const { data, error } = await supabase
    .from("installment_payments")
    .select("id")
    .eq("user_id", userId)
    .eq("transaction_id", transactionId)
    .eq("transaction_origin", "created")
    .maybeSingle();
  if (error) {
    if (["42P01", "PGRST205", "42703"].includes(error.code ?? "")) return false;
    console.error("Database error checking installment ownership:", error.message);
    return "error";
  }
  return Boolean(data);
}

/** Number of this user's transactions using a category (null if the count failed). */
export async function countCategoryUsage(supabase: ServerClient, userId: string, categoryId: string) {
  const { count, error } = await supabase
    .from("transactions")
    .select("id", { count: "exact", head: true })
    .eq("category_id", categoryId)
    .eq("user_id", userId);
  if (error) {
    console.error("Database error checking category usage:", error.message);
    return null;
  }
  return count ?? 0;
}
